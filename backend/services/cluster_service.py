from pathlib import Path
import pandas as pd


REPORTS_DIR = Path(__file__).resolve().parents[2] / "reports"

CLUSTERS_FILE = REPORTS_DIR / "clusters.csv"
CLUSTER_INFO_FILE = REPORTS_DIR / "cluster_info.csv"


def get_cluster_data(limit: int = 100):
    """
    Load consumption cluster assignments and cluster information
    generated by the clustering component.
    """

    if not CLUSTERS_FILE.exists():
        raise FileNotFoundError(
            f"Cluster output file not found: {CLUSTERS_FILE}"
        )

    if not CLUSTER_INFO_FILE.exists():
        raise FileNotFoundError(
            f"Cluster information file not found: {CLUSTER_INFO_FILE}"
        )

    clusters_df = pd.read_csv(CLUSTERS_FILE)
    info_df = pd.read_csv(CLUSTER_INFO_FILE)

    # Latest cluster records
    if clusters_df.empty:
        records = []
    else:
        records_df = clusters_df.tail(limit).copy()
        records_df = records_df.where(pd.notnull(records_df), None)
        records = records_df.to_dict(orient="records")

    # Cluster descriptions / summary
    if info_df.empty:
        cluster_info = []
    else:
        info_df = info_df.where(pd.notnull(info_df), None)
        cluster_info = info_df.to_dict(orient="records")

    return {
        "records": records,
        "cluster_info": cluster_info
    }