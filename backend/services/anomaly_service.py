from pathlib import Path
import pandas as pd


REPORTS_DIR = Path(__file__).resolve().parents[2] / "reports"

ANOMALY_FILE = REPORTS_DIR / "anomalies.csv"


def get_anomaly_data(limit: int = 100):
    """
    Load anomaly detection results generated by the anomaly
    detection component.
    """

    if not ANOMALY_FILE.exists():
        raise FileNotFoundError(
            f"Anomaly output file not found: {ANOMALY_FILE}"
        )

    df = pd.read_csv(ANOMALY_FILE)

    if df.empty:
        return []

    # Return the latest anomaly records
    df = df.tail(limit).copy()

    # Convert missing values to JSON-safe values
    df = df.where(pd.notnull(df), None)

    return df.to_dict(orient="records")