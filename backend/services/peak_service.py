from pathlib import Path
import pandas as pd


REPORTS_DIR = Path(__file__).resolve().parents[2] / "reports"

PEAK_FILE = REPORTS_DIR / "peak_predictions.csv"


def get_peak_data(limit: int = 30):
    """
    Load the latest peak prediction results generated by the peak
    prediction component.
    """

    if not PEAK_FILE.exists():
        raise FileNotFoundError(
            f"Peak prediction output file not found: {PEAK_FILE}"
        )

    df = pd.read_csv(PEAK_FILE)

    if df.empty:
        return []

    # Convert pandas missing values to JSON-safe values
    df = df.where(pd.notnull(df), None)

    # Return only the latest requested records
    df = df.tail(limit).copy()

    return df.to_dict(orient="records")